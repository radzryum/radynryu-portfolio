'use strict';

// Recolors signature ink to official black for PDF output.
// Website signature pads keep their own colors; only the PDF embeds change.
//
// pngjs is pure JS so Vercel serverless bundles include it.
const { PNG } = require('pngjs');

// Official document ink (near-black).
const INK_R = 26;
const INK_G = 26;
const INK_B = 26;

// Pixels lighter than this are treated as paper/background and made transparent
// (protects uploaded signature photos with opaque white backgrounds).
const PAPER_LUMINANCE = 242;
// Edge pixels between EDGE_FADE_START and PAPER_LUMINANCE keep a proportional
// alpha so anti-aliased strokes stay smooth instead of vanishing.
const EDGE_FADE_START = 200;

function luminance(r, g, b) {
  return 0.299 * r + 0.587 * g + 0.114 * b;
}

// Returns recolored PNG bytes, or throws when the input is not a decodable PNG.
function recolorPngToInk(buffer) {
  const png = PNG.sync.read(Buffer.from(buffer));
  const data = png.data;
  for (let i = 0; i < data.length; i += 4) {
    const alpha = data[i + 3];
    if (alpha < 8) {
      data[i + 3] = 0;
      continue;
    }
    const lum = luminance(data[i], data[i + 1], data[i + 2]);
    if (lum >= PAPER_LUMINANCE) {
      data[i + 3] = 0;
      continue;
    }
    data[i] = INK_R;
    data[i + 1] = INK_G;
    data[i + 2] = INK_B;
    if (lum > EDGE_FADE_START) {
      data[i + 3] = Math.round(alpha * (PAPER_LUMINANCE - lum) / (PAPER_LUMINANCE - EDGE_FADE_START));
    }
  }
  return PNG.sync.write(png);
}

function decodeDataUrl(source) {
  if (!source) return null;
  const match = /^data:(image\/(?:png|jpe?g));base64,(.+)$/i.exec(source);
  if (match) {
    return { contentType: match[1].toLowerCase(), bytes: Buffer.from(match[2], 'base64') };
  }
  // Fallback for raw base64 strings without the data URL prefix.
  // Signatures generated by the app are PNGs.
  return { contentType: 'image/png', bytes: Buffer.from(source, 'base64') };
}

// Embeds a signature with ink remapped to official black. Returns the embedded
// image, or null when the source is not a PNG data URL (caller falls back
// to the regular embed path, e.g. for JPG uploads and remote URLs).
async function embedSignatureInk(pdf, source) {
  try {
    const decoded = decodeDataUrl(source);
    if (!decoded || !/png/i.test(decoded.contentType)) return null;
    const inkBytes = recolorPngToInk(decoded.bytes);
    return await pdf.embedPng(inkBytes);
  } catch (err) {
    console.error('embedSignatureInk error:', err);
    return null;
  }
}

module.exports = { recolorPngToInk, embedSignatureInk, SIGNATURE_INK: { r: INK_R, g: INK_G, b: INK_B } };
